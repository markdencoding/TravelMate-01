/**
 * Searches curated location records using prefix, word match, or keyword match.
 */
export function searchCuratedLocations(query: string, maxResults: number = 10): LocationRecord[] {
  const clean = query.trim().toLowerCase();
  if (clean.length < 2) return [];

  const tokens = clean.split(/\s+/).filter(Boolean);

  const matched = CURATED_LOCATIONS.filter((loc) => {
    const nameLower = loc.name.toLowerCase();
    const secLower = loc.secondaryText.toLowerCase();
    const countryLower = loc.country.toLowerCase();

    // Direct substring in name or secondary text
    if (nameLower.includes(clean) || secLower.includes(clean) || countryLower.includes(clean)) {
      return true;
    }

    // Match keywords or all tokens
    const matchAllTokens = tokens.every(
      (tok) =>
        nameLower.includes(tok) ||
        secLower.includes(tok) ||
        countryLower.includes(tok) ||
        loc.keywords.some((kw) => kw.includes(tok))
    );

    return matchAllTokens;
  });

  // Sort: exact startsWith name first, then name contains, then others
  matched.sort((a, b) => {
    const aName = a.name.toLowerCase();
    const bName = b.name.toLowerCase();
    const aStarts = aName.startsWith(clean);
    const bStarts = bName.startsWith(clean);
    if (aStarts && !bStarts) return -1;
    if (!aStarts && bStarts) return 1;
    return 0;
  });

  return matched.slice(0, maxResults);
}

/**
 * Converts a LocationRecord to a PlaceSuggestion
 */
export function locationToSuggestion(loc: LocationRecord): PlaceSuggestion {
  return {
    id: loc.id,
    name: loc.name,
    secondaryText: loc.secondaryText,
    country: loc.country,
    countryCode: loc.countryCode,
    kind: loc.kind,
    latitude: loc.latitude,
    longitude: loc.longitude,
  };
}

/**
 * Converts a LocationRecord to a PlaceItem
 */
export function locationToPlaceItem(loc: LocationRecord): PlaceItem {
  return {
    id: loc.id,
    name: loc.name,
    displayName: `${loc.name}, ${loc.secondaryText}`,
    country: loc.country,
    category: loc.category,
    categoryLabel: loc.categoryLabel,
    latitude: loc.latitude,
    longitude: loc.longitude,
    type: loc.kind,
    class: loc.category,
  };
}
