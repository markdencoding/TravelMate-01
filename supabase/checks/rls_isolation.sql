-- ==============================================================================
-- File: supabase/checks/rls_isolation.sql
-- Description: Transactional RLS & Cross-Tenant Security Isolation Test.
-- WARNING: Run this verification ONLY in a development or local test environment.
-- The script runs inside a transaction and ends with ROLLBACK, leaving zero data.
-- ==============================================================================

begin;

do $$
declare
  v_user_a uuid := 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa';
  v_user_b uuid := 'bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb';
  v_trip_a uuid;
  v_dest_a uuid;
  v_item_a uuid;
  v_notif_a uuid;
  v_count integer;
  v_error_caught boolean;
  v_profile_role text;
  v_profile_active boolean;
begin
  raise notice '>>> Starting TravelMate RLS & Security Isolation Verification...';

  -- --------------------------------------------------------------------------
  -- TEST 1: Auth Trigger Profile Creation & Privilege Defaults
  -- --------------------------------------------------------------------------
  -- Create fake auth users in auth.users
  insert into auth.users (id, email, raw_user_meta_data)
  values
    (v_user_a, 'user_a@travelmate.test', '{"full_name": "Explorer Alpha", "role": "admin"}'::jsonb),
    (v_user_b, 'user_b@travelmate.test', '{"full_name": "Explorer Beta", "role": "admin"}'::jsonb);

  -- Verify User A profile was generated by trigger with enforced 'traveler' role
  select role, is_active into v_profile_role, v_profile_active
  from public.profiles
  where id = v_user_a;

  if v_profile_role != 'traveler' or v_profile_active != true then
    raise exception 'TEST 1 FAILED: Trigger failed to enforce role=traveler or is_active=true (got role=%, active=%)',
      v_profile_role, v_profile_active;
  end if;
  raise notice '✓ TEST 1 PASSED: Auth trigger created profile with forced role="traveler" and is_active=true.';

  -- --------------------------------------------------------------------------
  -- TEST 2: Self-Promotion & Status Tampering Block
  -- --------------------------------------------------------------------------
  -- Impersonate User A
  set local role authenticated;
  set local "request.jwt.claims" = '{"sub": "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa", "role": "authenticated"}';

  v_error_caught := false;
  begin
    update public.profiles set role = 'admin' where id = v_user_a;
  exception when others then
    v_error_caught := true;
  end;

  if not v_error_caught then
    raise exception 'TEST 2A FAILED: User A was able to update their role to admin!';
  end if;

  v_error_caught := false;
  begin
    update public.profiles set is_active = false where id = v_user_a;
  exception when others then
    v_error_caught := true;
  end;

  if not v_error_caught then
    raise exception 'TEST 2B FAILED: User A was able to tamper with their is_active status!';
  end if;
  raise notice '✓ TEST 2 PASSED: Privilege escalation guard prevented unauthorized role and is_active changes.';

  -- --------------------------------------------------------------------------
  -- TEST 3: User A Creates Valid Trip, Destination, Itinerary, Expense, Notification
  -- --------------------------------------------------------------------------
  insert into public.trips (
    user_id, title, start_date, end_date, budget_amount, currency
  )
  values (
    v_user_a, 'Alpha Autumn Expedition', '2026-10-12', '2026-10-20', 2500.00, 'USD'
  )
  returning id into v_trip_a;

  insert into public.destinations (
    trip_id, name, country, latitude, longitude, order_index
  )
  values (
    v_trip_a, 'Kyoto Higashiyama', 'Japan', 34.994856, 135.785042, 1
  )
  returning id into v_dest_a;

  insert into public.itinerary_items (
    trip_id, destination_id, day_date, title, category, cost, currency
  )
  values (
    v_trip_a, v_dest_a, '2026-10-14', 'Kiyomizu-dera Sunrise Walk', 'sightseeing', 45.00, 'USD'
  )
  returning id into v_item_a;

  insert into public.expenses (
    trip_id, itinerary_item_id, category, title, amount, currency, expense_date
  )
  values (
    v_trip_a, v_item_a, 'sightseeing', 'Temple Entry Fee', 45.00, 'USD', '2026-10-14'
  );

  insert into public.notifications (
    user_id, trip_id, type, title, message
  )
  values (
    v_user_a, v_trip_a, 'budget', 'Welcome to Kyoto', 'Your expedition is configured.'
  )
  returning id into v_notif_a;

  raise notice '✓ TEST 3 PASSED: User A successfully created trip and child records.';

  -- --------------------------------------------------------------------------
  -- TEST 4: Cross-Tenant Read Isolation (User B cannot read User A's data)
  -- --------------------------------------------------------------------------
  -- Switch session to User B
  set local role authenticated;
  set local "request.jwt.claims" = '{"sub": "bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb", "role": "authenticated"}';

  select count(*) into v_count from public.trips where id = v_trip_a;
  if v_count != 0 then raise exception 'TEST 4A FAILED: User B can read User A trips!'; end if;

  select count(*) into v_count from public.destinations where trip_id = v_trip_a;
  if v_count != 0 then raise exception 'TEST 4B FAILED: User B can read User A destinations!'; end if;

  select count(*) into v_count from public.itinerary_items where trip_id = v_trip_a;
  if v_count != 0 then raise exception 'TEST 4C FAILED: User B can read User A itinerary items!'; end if;

  select count(*) into v_count from public.expenses where trip_id = v_trip_a;
  if v_count != 0 then raise exception 'TEST 4D FAILED: User B can read User A expenses!'; end if;

  select count(*) into v_count from public.notifications where id = v_notif_a;
  if v_count != 0 then raise exception 'TEST 4E FAILED: User B can read User A notifications!'; end if;

  raise notice '✓ TEST 4 PASSED: Tenant isolation confirmed. User B cannot view any records of User A.';

  -- --------------------------------------------------------------------------
  -- TEST 5: Cross-Tenant Write Isolation (User B cannot modify or inject child items)
  -- --------------------------------------------------------------------------
  -- Attempt 5A: User B tries to update User A's trip
  update public.trips set title = 'Hacked Trip' where id = v_trip_a;
  -- With RLS, 0 rows are affected
  reset role;
  select title into v_profile_role from public.trips where id = v_trip_a;
  if v_profile_role = 'Hacked Trip' then
    raise exception 'TEST 5A FAILED: User B was able to modify User A trip!';
  end if;

  -- Attempt 5B: User B tries to insert an item into User A's trip
  set local role authenticated;
  set local "request.jwt.claims" = '{"sub": "bbbbbbbb-bbbb-bbbb-bbbb-bbbbbbbbbbbb", "role": "authenticated"}';

  v_error_caught := false;
  begin
    insert into public.itinerary_items (
      trip_id, day_date, title, category
    )
    values (
      v_trip_a, '2026-10-15', 'Malicious Activity', 'sightseeing'
    );
  exception when others then
    v_error_caught := true;
  end;

  if not v_error_caught then
    raise exception 'TEST 5B FAILED: User B was able to insert an activity into User A trip!';
  end if;

  -- Attempt 5C: User B creates their own trip but tries to attach User A's destination
  declare
    v_trip_b uuid;
  begin
    insert into public.trips (user_id, title, start_date, end_date)
    values (v_user_b, 'Trip Beta', '2026-10-12', '2026-10-20')
    returning id into v_trip_b;

    v_error_caught := false;
    begin
      -- Composite FK (trip_id, destination_id) prevents referencing User A's destination!
      insert into public.itinerary_items (
        trip_id, destination_id, day_date, title, category
      )
      values (
        v_trip_b, v_dest_a, '2026-10-14', 'Cross-referenced item', 'sightseeing'
      );
    exception when others then
      v_error_caught := true;
    end;

    if not v_error_caught then
      raise exception 'TEST 5C FAILED: Composite FK did not prevent attaching foreign destination!';
    end if;
  end;
  raise notice '✓ TEST 5 PASSED: Cross-tenant injection and composite foreign key defenses verified.';

  -- --------------------------------------------------------------------------
  -- TEST 6: Constraint Validations (Dates, Amounts, Boundaries)
  -- --------------------------------------------------------------------------
  -- Switch back to User A
  set local role authenticated;
  set local "request.jwt.claims" = '{"sub": "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa", "role": "authenticated"}';

  -- 6A: Invalid Trip Dates (end_date < start_date)
  v_error_caught := false;
  begin
    insert into public.trips (user_id, title, start_date, end_date)
    values (v_user_a, 'Bad Dates Trip', '2026-10-20', '2026-10-10');
  exception when others then
    v_error_caught := true;
  end;
  if not v_error_caught then raise exception 'TEST 6A FAILED: End date before start date was allowed!'; end if;

  -- 6B: Negative Expense Amount
  v_error_caught := false;
  begin
    insert into public.expenses (trip_id, category, title, amount, currency, expense_date)
    values (v_trip_a, 'food', 'Negative Ramen', -15.00, 'USD', '2026-10-14');
  exception when others then
    v_error_caught := true;
  end;
  if not v_error_caught then raise exception 'TEST 6B FAILED: Negative expense amount was allowed!'; end if;

  -- 6C: Out-of-Bounds Itinerary Date
  v_error_caught := false;
  begin
    insert into public.itinerary_items (trip_id, day_date, title, category)
    values (v_trip_a, '2026-11-05', 'Out of range tour', 'sightseeing');
  exception when others then
    v_error_caught := true;
  end;
  if not v_error_caught then raise exception 'TEST 6C FAILED: Activity date outside trip dates was allowed!'; end if;

  -- 6D: Guard Trip Date Contraction with Existing Activities
  v_error_caught := false;
  begin
    -- Trip has activity on 2026-10-14. Trying to move end_date to 2026-10-13 should fail!
    update public.trips set end_date = '2026-10-13' where id = v_trip_a;
  exception when others then
    v_error_caught := true;
  end;
  if not v_error_caught then raise exception 'TEST 6D FAILED: Trip date contraction past existing activity was allowed!'; end if;

  raise notice '✓ TEST 6 PASSED: Date constraints, negative amount checks, and boundary guards verified.';
  raise notice '>>> ALL RLS & INTEGRITY TESTS PASSED SUCCESSFULLY! Rolling back transaction.';
end;
$$;

rollback;
